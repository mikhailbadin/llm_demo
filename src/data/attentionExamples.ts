import { prevWordScores } from '@/lib/attention';

export interface AttentionHead {
  name: string;
  description: string;
  scores: number[][];
}

export interface AttentionExample {
  id: string;
  label: string;
  tokens: string[];
  heads: AttentionHead[];
  /** индекс токена, который интересно выбрать по умолчанию */
  focus: number;
  note: string;
}

