const paris: number[][] = [
  // Париж  —   это  столица  Франции
  [3.0, 0.5, 0.0, 2.0, 1.5], // Париж
  [3.0, 1.0, 1.0, 0.0, 0.0], // —
  [1.0, 3.0, 1.5, 1.0, 0.0], // это
  [5.0, 0.5, 1.5, 2.0, 4.5], // столица → Париж, Франции
  [4.0, 0.0, 0.5, 4.5, 2.0], // Франции → столица, Париж
];

function build(id: string, label: string, tokens: string[], semantic: number[][], focus: number, note: string): AttentionExample {
  return {
    id,
    label,
    tokens,
    focus,
    note,
    heads: [
      { name: 'Голова 1: предыдущее слово', description: 'Смотрит в основном на слово слева — так модель улавливает локальный порядок.', scores: prevWordScores(tokens.length) },
      { name: 'Голова 2: смысловая связь', description: 'Связывает местоимения с тем, к чему они относятся, и слова, которые зависят друг от друга по смыслу.', scores: semantic },
    ],
  };
}

export const ATTENTION_EXAMPLES: AttentionExample[] = [
  build('cat', 'Кот сел на коврик, потому что он устал', ['Кот', 'сел', 'на', 'коврик', ',', 'потому', 'что', 'он', 'устал'], cat, 7, 'Кто «он»? Вторая голова уверенно смотрит на «Кот».'),
  build('book', 'Я положил книгу на стол и взял её', ['Я', 'положил', 'книгу', 'на', 'стол', 'и', 'взял', 'её'], book, 7, 'Что «её»? Слово «книгу» стоит далеко, но внимание не зависит от расстояния.'),
  build('paris', 'Париж — это столица Франции', ['Париж', '—', 'это', 'столица', 'Франции'], paris, 3, 'Слово «столица» собирает информацию сразу из двух мест: «Париж» и «Франции».'),
];
