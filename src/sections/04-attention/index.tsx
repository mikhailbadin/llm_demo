import { useEffect } from 'react';
import { Callout, Formula, M, SectionHero, Summary, Term } from '@/components/ui';
import { SceneContainer } from '@/components/three-shell/SceneContainer';
import { attentionStore } from '@/scenes/Attention/store';
import { SoftmaxPlayground } from './widgets/SoftmaxPlayground';
import { AttentionStepByStep } from './widgets/AttentionStepByStep';
import { AttentionHeatmap } from './widgets/AttentionHeatmap';
import { AttentionControls } from './widgets/AttentionControls';
import { MultiHeadFigure } from './widgets/MultiHeadFigure';

export default function AttentionSection() {
  // По умолчанию запрос — «он»: так и виджеты, и сцена сразу показывают веса.
  useEffect(() => {
    const st = attentionStore.getState();
    if (!st.selectedId) st.select('t7');
  }, []);
  return (
    <>
      <SectionHero
        id="attention"
        learn={['Зачем токенам «смотреть» друг на друга и что такое Query, Key и Value', 'Как оценки превращаются в веса через softmax', 'Что делают несколько голов и причинная маска']}
      />

      <h2>Одного эмбеддинга мало</h2>
      <p>
        У слова «ключ» один эмбеддинг, но в «ключ от двери» и «ключ в лесу» оно значит разное. Смысл зависит от контекста. Значит, вектор токена нужно{' '}
        <em>обновить</em>, посмотрев на соседей. Механизм, который это делает, называется <Term id="attention">вниманием</Term>, и это главное изобретение, на
        котором стоят современные модели.
      </p>
      <p>Интуиция — поиск в библиотеке. Каждый токен создаёт три вектора:</p>
      <ul>
        <li>
          <Term id="query">Query</Term> — «что я ищу». Для местоимения «он»: «ищу существительное мужского рода, о котором шла речь».
        </li>
        <li>
          <Term id="key">Key</Term> — «что я собой представляю», ярлык на корешке книги. Для «Кот»: «существительное, мужской род, подлежащее».
        </li>
        <li>
          <Term id="value">Value</Term> — «что я могу отдать», содержимое книги.
        </li>
      </ul>
      <p>
        Запрос сравнивают с каждым ключом: чем лучше совпадают, тем выше оценка. Оценки превращают в веса, и токен получает взвешенную сумму значений — в основном
        от тех, чьи ключи подошли.
      </p>

      <h2>Softmax: как оценки становятся весами</h2>
      <p>
        Оценки могут быть любыми числами, а нам нужны веса: неотрицательные и с суммой 1. Эту работу делает <Term id="softmax">softmax</Term>. Эта же функция
        стоит на самом выходе модели, превращая <Term id="logits">логиты</Term> в вероятности токенов, так что стоит разобраться с ней один раз и навсегда.
      </p>
      <Formula tex={String.raw`\operatorname{softmax}(z)_i = \frac{e^{z_i}}{\sum_{j} e^{z_j}}`} caption={<>Экспонента делает все числа положительными, деление на сумму — нормирует. Большие zᵢ получают почти всё, маленькие — почти ничего.</>} />
      <SoftmaxPlayground />

      <h2>Формула внимания</h2>
      <Formula
        tex={String.raw`\operatorname{Attention}(Q, K, V) = \operatorname{softmax}\!\left(\frac{QK^{\top}}{\sqrt{d_k}}\right) V`}
        caption={
          <>
            <M tex="QK^{\top}" /> — таблица оценок «каждый запрос против каждого ключа». Деление на <M tex="\sqrt{d_k}" /> не даёт оценкам расти вместе с
            размерностью. Softmax по строкам даёт веса, умножение на V — взвешенную сумму значений.
          </>
        }
      />
      <Formula tex={String.raw`Q = XW_Q, \qquad K = XW_K, \qquad V = XW_V`} caption={<>Все три вектора получаются из одних и тех же входных векторов X умножением на три обучаемые матрицы. Именно эти матрицы модель и учит.</>} />
      <Callout kind="try">
        Пройдите вычисление по шагам для одного запроса. Затем посмотрите на всю матрицу сразу и включите маску — веса в строке перераспределятся.
      </Callout>
      <AttentionStepByStep />
      <AttentionHeatmap />

      <h2>Внимание в объёме</h2>
      <Callout kind="try">
        В сцене ниже дуги идут от запроса к ключам, толщина дуги — вес. Столбики под токенами — те же веса в виде гистограммы. Нажмите на любой токен, переключите
        голову, включите маску. Экскурсия проведёт по пяти ключевым идеям.
      </Callout>
      <SceneContainer
        sceneId="attention"
        title="Дуги внимания"
        store={attentionStore}
        overlay={<AttentionControls />}
        legend={<p>Жёлтая сфера — токен-запрос. Дуги окрашены от фиолетового (слабое внимание) к жёлтому (сильное). Кольцо вокруг запроса — внимание на самого себя.</p>}
      />

      <h2>Много голов и маска</h2>
      <p>
        Одного «взгляда» мало: одновременно полезно следить и за порядком слов, и за тем, к чему относится местоимение, и за согласованием. Поэтому внимание
        делают <Term id="multi-head">многоголовым</Term>: несколько наборов матриц Q, K, V работают параллельно, каждый в своём подпространстве, а результаты
        склеиваются.
      </p>
      <MultiHeadFigure />
      <p>
        И последнее: при генерации модель не должна подглядывать вперёд, ведь следующих токенов ещё нет. <Term id="causal-mask">Причинная маска</Term> ставит{' '}
        <M tex="-\infty" /> на все оценки «в будущее», и после softmax они дают ровно 0. Так одна и та же модель может и обучаться на целых текстах, и генерировать
        их слева направо.
      </p>
      <Callout kind="hint" title="Почему это работает так хорошо">
        Внимание не зависит от расстояния: токен в конце абзаца может напрямую «взять» информацию у токена в начале. Старые рекуррентные сети передавали её по
        цепочке и по дороге теряли. Плюс все токены обрабатываются параллельно — это делает обучение быстрым на GPU.
      </Callout>

      <Summary>
        <ul>
          <li>Внимание обновляет вектор токена, собирая информацию у других токенов пропорционально тому, насколько их ключи подходят к его запросу.</li>
          <li>Softmax превращает оценки в веса с суммой 1; та же функция даёт вероятности на выходе модели.</li>
          <li>Много голов ловят разные типы связей; причинная маска запрещает смотреть в будущее.</li>
        </ul>
      </Summary>
    </>
  );
}
